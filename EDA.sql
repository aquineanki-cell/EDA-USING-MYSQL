FROM ELECTRONICS_DATA;
-- BY EXPORTING THE TABLE WHICH THIS QUERY WILL RETURN.
-- WE CAN CREATE AN SCATTERPLOT TO FIND THE RELATIONSHIP BETWEEN REVIEWS_COUNT AND AVG_RATING.

-- COVARIANCE:
SELECT SUM(
(AVG_RATING - (SELECT AVG(AVG_RATING) FROM ELECTRONICS_DATA)) *
(REVIEWS_COUNT - (SELECT AVG(REVIEWS_COUNT) FROM ELECTRONICS_DATA)))/
(COUNT(*) - 1) AS COVARIANCE_OF_RATING_AND_REVIEWS
FROM ELECTRONICS_DATA;
-- THE COVARIANCE IS : 4.03297159208412
-- WHICH MEANS BOTH THE COLUMNS HAVE A POSITIVE RELATION.
-- I WILL VERIFY IT BY CHECKING THE CORRELATION.

-- CORRELATION:
SELECT (ROUND(SUM(
(AVG_RATING - (SELECT AVG(AVG_RATING) FROM ELECTRONICS_DATA)) *
(REVIEWS_COUNT - (SELECT AVG(REVIEWS_COUNT) FROM ELECTRONICS_DATA)))/
(COUNT(*) - 1),2)) / (STD(AVG_RATING)* STD(REVIEWS_COUNT))
AS CORRELATION FROM ELECTRONICS_DATA;

-- CORREALATION IS : 0.013438078309843306
-- THIS IS A VERY WEAK POSITIVE RELATIONSHIP, WHICH WE CAN IGNORE.

-- SLOPE: Slope represents the "rate of change" or the trend line between two variables. 
-- It tells us how much we expect the Y variable to change for every 1-unit increase in the X variable.

SELECT SUM(
(AVG_RATING - (SELECT AVG(AVG_RATING) FROM ELECTRONICS_DATA)) *
(REVIEWS_COUNT - (SELECT AVG(REVIEWS_COUNT) FROM ELECTRONICS_DATA)))/SUM(
POWER(AVG_RATING - (SELECT AVG(AVG_RATING) FROM ELECTRONICS_DATA),2)) AS SLOPE
FROM ELECTRONICS_DATA;

-- SLOPE VALUE IS : 19.26368144640428
-- WHICH MEANS: For every 1-point increase in a product's average rating, 
-- we can generally expect to see an increase of about 19.26 reviews. 
-- NOTE: This shows a correlation (trend), not causation. We also cannot predict 
-- the exact review count using just this slope without also calculating the Y-intercept!

