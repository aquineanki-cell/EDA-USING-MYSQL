-- AND WE CAN CLAIM THEM AS OUTLIERS AND NECESSARY ACTION IF REQUIRED.
SELECT * FROM ELECTRONICS_DATA WHERE PRICE < (@Q1-1.5*(@Q3-@Q1)) OR 
