-- PERCENTILE
-- THERE IS NO SUCH FUNCTION IN MYSQL THROUGH WHICH YOU CAN FIND PERCENTILE.
-- THERE IS WAY BY WHICH WE CAN FIND THE PERCENTILE FOR EACH VALUES IN THE COLUMN. 
-- THAT IS NOT THE MOST EFFECIENT WAY TO FIND OUT PERCENTILES IN MYSQL.
SELECT PRICE,MAX(PERCENTILES) FROM 
(SELECT PRICE,ROUND(PERCENT_RANK() OVER (ORDER BY PRICE),2) AS PERCENTILES
FROM ELECTRONICS_DATA) K
GROUP BY PRICE;
-- THIS IS THE LOGIC I HAVE CREATED. MAXIMUM PERCENTILE VALUES WILL BE CONSIDERED AS PERCENTILE VALUES.
-- I WILL CREATE A STORED PROCEDURE USING THIS LOGIC TO GET THE PRICE BY PERCENTILE.
DELIMITER $$
CREATE PROCEDURE GETRPICEBYPERCENTILE( IN PERCENTILEVALUE DECIMAL(3,2),OUT PRICE_LIMIT DECIMAL(10,2))
BEGIN 
SELECT MAX(PRICE) INTO PRICE_LIMIT FROM(
SELECT PRICE,ROUND(PERCENT_RANK() OVER (ORDER BY PRICE),2) AS PERCENTILES
FROM ELECTRONICS_DATA ) K 
WHERE PERCENTILES = PERCENTILEVALUE;
END $$
DELIMITER ;
-- THE STORED PROCEDURE HAS BEEN CREATED SUCESSFULLY.
-- THIS PROCEDURE TAKES THE 'PERCENTILE' AND THE VARIABLE AS INPUT TO SHOW THE PRICE.
CALL GETRPICEBYPERCENTILE(0.25,@Q1);
SELECT @Q1; -- OUTPUT IS : 726.28,,, THIS IS THE 25TH PERCENTILE.

CALL GETRPICEBYPERCENTILE(0.50,@Q2);
SELECT @Q2; -- OUTPUT IS : 1516.64 ,, THIS IS THE 50TH PERCENTILE.

CALL GETRPICEBYPERCENTILE(0.75,@Q3);
SELECT @Q3; -- OUTPUT IS : 2209.00 ,, THIS IS THE 75TH PERCENTILE.

CALL GETRPICEBYPERCENTILE(1,@Q4);
SELECT @Q4; -- OUTPUT IS : 2998.81 ,, THIS IS THE 100TH PERCENTILE.

-- TO MENTION ALL THE VALUES IN ONE QUERY.
CALL GETRPICEBYPERCENTILE(0.25,@Q1);
CALL GETRPICEBYPERCENTILE(0.50,@Q2);
CALL GETRPICEBYPERCENTILE(0.75,@Q3);
CALL GETRPICEBYPERCENTILE(1,@Q4);

SELECT @Q1 AS 'QUATER_1',@Q2 AS 'MEDIAN',
