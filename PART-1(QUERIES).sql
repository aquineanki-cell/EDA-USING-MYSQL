SELECT 
    Price,
    CAST(
        SUBSTRING_INDEX(
            SUBSTRING_INDEX(Price, '$', -1), -- Step 1: Get everything after the $
        ' ', 1)                              -- Step 2: Get everything before the first space
    AS DECIMAL(10,2)) AS Numeric_Price       -- Step 3: Convert to a number
