-- THEN I ENDED UP USING THE REGEXP_SUBSTR() FUNCTION IN WHICH I DIFFRENTIATED THE NUMERIC VALUES.
SELECT 
    Price,
    CAST(REGEXP_SUBSTR(Price, '[0-9]+(\\.[0-9]+)?') AS DECIMAL(10,2)) AS Numeric_Price
FROM 
    electronics_data;
    
UPDATE ELECTRONICS_DATA SET 
PRICE = CAST(REGEXP_SUBSTR(Price, '[0-9]+(\\.[0-9]+)?') AS DECIMAL(10,2))
WHERE PRICE LIKE '%THROUGH SPECIAL EVENT%';

